	private final String[] rows;

	PixelIcons(String... rows) {
		this.rows = rows;
	}

	int width() {
		int w = 0;
		for (String row : rows) {
			w = Math.max(w, row.length());
		}
		return w;
	}

	int height() {
		return rows.length;
	}

	/** Draws the glyph with its top-left corner at (x, y); horizontal runs of one color become one rectangle. */
	void draw(GuiGraphicsExtractor graphics, int x, int y, int main, int secondary) {
		for (int r = 0; r < rows.length; r++) {
			String row = rows[r];
			int c = 0;
			while (c < row.length()) {
				char ch = row.charAt(c);
				int end = c;
				while (end < row.length() && row.charAt(end) == ch) {
					end++;
				}
				if (ch == '#') {
					graphics.fill(x + c, y + r, x + end, y + r + 1, main);
				} else if (ch == 'o') {
					graphics.fill(x + c, y + r, x + end, y + r + 1, secondary);
				}
				c = end;
			}
		}
	}
